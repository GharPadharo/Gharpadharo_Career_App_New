export function getActiveJobs() {
  return mockJobs.filter((job) => (job.status || "active").toLowerCase() === "active");
}

export function getDraftJobs() {
  return mockJobs.filter((job) => (job.status || "").toLowerCase() === "draft");
}

export function getClosedJobs() {
  return mockJobs.filter((job) => (job.status || "").toLowerCase() === "closed");
}

export function getJobById(id) {
  return mockJobs.find((job) => job.id === id);
}
